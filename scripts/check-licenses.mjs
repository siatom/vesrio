#!/usr/bin/env node
/**
 * Third-party license audit for Vesrio.
 *
 * Collects Node (pnpm) and Rust (cargo metadata) dependency licenses, checks
 * them against a permissive allowlist, and writes docs/licenses-report.md.
 *
 * Usage: node scripts/check-licenses.mjs [--check]
 *   --check  fail without rewriting the report when a license is not allowed
 */
import { execFileSync, execSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')

// Permissive licenses accepted for shipped dependencies. Weak copyleft
// (MPL-2.0) is accepted for unmodified dependencies; see docs/security-audit.md.
const ALLOWED = new Set([
  '0BSD',
  'Apache-2.0',
  'BlueOak-1.0.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'BSL-1.0',
  'CC0-1.0',
  'CDLA-Permissive-2.0',
  'ISC',
  'MIT',
  'MIT-0',
  'MPL-2.0',
  'Python-2.0',
  'Unicode-3.0',
  'Unicode-DFS-2016',
  'Unlicense',
  'Zlib',
])

// Packages whose package.json omits the license field while the shipped
// license file is permissive. Keep this list tiny and verify the file.
const LICENSE_OVERRIDES = new Map([['khroma', 'MIT']])

function normalizeExpression(expression) {
  return expression
    .replace(/[()]/g, ' ')
    .replace(/\//g, ' OR ')
    .replace(/\s+/g, ' ')
    .trim()
}

/** Evaluate SPDX-like AND/OR expressions against the allowlist. */
function isAllowed(expression, packageName) {
  if (packageName === 'vesrio' && !expression) {
    return { allowed: true, reason: 'first-party workspace package' }
  }
  if (!expression) return { allowed: false, reason: 'missing license field' }

  // Every AND branch must be satisfied; an OR branch is satisfied by any side.
  const branches = normalizeExpression(expression)
    .split(/\s+AND\s+/i)
    .map((branch) => branch.trim())
  for (const branch of branches) {
    const options = branch
      .split(/\s+OR\s+/i)
      .map((option) => option.trim())
      .filter(Boolean)
    const satisfied = options.some((option) => {
      // "Apache-2.0 WITH LLVM-exception" is still governed by Apache-2.0.
      const base = option.split(/\s+WITH\s+/i)[0]
      return ALLOWED.has(option) || ALLOWED.has(base)
    })
    if (!satisfied) return { allowed: false, reason: `unlisted license ${branch}` }
  }
  return { allowed: true, reason: 'allowed' }
}

function readNodeLicenses() {
  const raw = execSync('pnpm licenses list --json', {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 256 * 1024 * 1024,
  })
  const grouped = JSON.parse(raw)
  const entries = []
  for (const [license, packages] of Object.entries(grouped)) {
    for (const pkg of packages) {
      entries.push({
        ecosystem: 'node',
        name: pkg.name,
        version: (pkg.versions ?? []).join(', '),
        license: LICENSE_OVERRIDES.get(pkg.name) ?? license,
      })
    }
  }
  return entries
}

function readRustLicenses() {
  const raw = execFileSync(
    'cargo',
    ['metadata', '--format-version', '1', '--locked', '--manifest-path', 'src-tauri/Cargo.toml'],
    { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 },
  )
  const metadata = JSON.parse(raw)
  return metadata.packages
    .filter((pkg) => pkg.source !== null || pkg.name === 'vesrio')
    .map((pkg) => ({
      ecosystem: 'rust',
      name: pkg.name,
      version: pkg.version,
      license: pkg.license ?? '',
    }))
}

function compareEntries(a, b) {
  return (
    a.ecosystem.localeCompare(b.ecosystem) ||
    a.name.localeCompare(b.name) ||
    a.version.localeCompare(b.version)
  )
}

const entries = [...readNodeLicenses(), ...readRustLicenses()].sort(compareEntries)
const violations = []
for (const entry of entries) {
  const verdict = isAllowed(entry.license, entry.name)
  entry.allowed = verdict.allowed
  entry.reason = verdict.reason
  if (!verdict.allowed) violations.push(entry)
}

const byLicense = new Map()
for (const entry of entries) {
  const key = entry.license || '(missing)'
  byLicense.set(key, (byLicense.get(key) ?? 0) + 1)
}

const nodeCount = entries.filter((entry) => entry.ecosystem === 'node').length
const rustCount = entries.length - nodeCount
const lines = [
  '# Third-party license report',
  '',
  '> Generated by `node scripts/check-licenses.mjs`. Do not edit by hand.',
  '',
  `- Node packages: ${nodeCount}`,
  `- Rust crates: ${rustCount}`,
  `- Total: ${entries.length}`,
  `- Result: ${violations.length === 0 ? 'PASS — all licenses are on the allowlist' : `FAIL — ${violations.length} unlisted`}`,
  '',
  'The allowlist accepts MIT, ISC, BSD-2/3-Clause, Apache-2.0, MPL-2.0 (unmodified),',
  'CC0-1.0, Unlicense, Zlib, BSL-1.0, BlueOak-1.0.0, Python-2.0, CDLA-Permissive-2.0,',
  'Unicode-3.0 and equivalent SPDX combinations. Weak copyleft (MPL-2.0) is used',
  'without modification and does not affect Vesrio source licensing.',
  '',
  '## Summary by license',
  '',
  '| License | Packages |',
  '| --- | --: |',
  ...[...byLicense.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([license, count]) => `| ${license.replaceAll('|', '\\|')} | ${count} |`),
  '',
  '## Package inventory',
  '',
  '| Ecosystem | Package | Version | License | Allowed |',
  '| --- | --- | --- | --- | --- |',
  ...entries.map(
    (entry) =>
      `| ${entry.ecosystem} | ${entry.name.replaceAll('|', '\\|')} | ${entry.version} | ${(entry.license || '(missing)').replaceAll('|', '\\|')} | ${entry.allowed ? 'yes' : 'no'} |`,
  ),
  '',
]

if (violations.length > 0) {
  lines.push('## Violations', '')
  for (const entry of violations) {
    lines.push(`- ${entry.ecosystem} ${entry.name}@${entry.version}: ${entry.reason}`)
  }
  lines.push('')
}

const report = lines.join('\n')
if (checkOnly) {
  process.stdout.write(
    `license check: ${entries.length} packages, ${violations.length} violation(s)\n`,
  )
} else {
  writeFileSync(join(root, 'docs', 'licenses-report.md'), report, 'utf8')
  process.stdout.write(
    `wrote docs/licenses-report.md (${entries.length} packages, ${violations.length} violation(s))\n`,
  )
}

if (violations.length > 0) {
  for (const entry of violations) {
    process.stderr.write(
      `UNLISTED ${entry.ecosystem} ${entry.name}@${entry.version}: ${entry.license}\n`,
    )
  }
  process.exitCode = 1
}
